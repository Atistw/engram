#!/bin/bash
# 排程二：月初決策掃描 + 修正 log 月審（每月 1 日 09:00）（cron 版；prompt 與 _schedules/排程範本.md 相同，改一邊要同步改另一邊）
set -euo pipefail

VAULT_DIR="${VAULT_DIR:-/path/to/your-knowledge-base}"   # 改成你 cron 主機上的實際路徑
LOG_DIR="$VAULT_DIR/_schedules/logs"
mkdir -p "$LOG_DIR"

cd "$VAULT_DIR"

claude -p "你是知識庫的決策掃描員。工作目錄：$VAULT_DIR

先讀 CLAUDE.md、DECISIONS.md、TASKS.md（讀到停讀邊界即可），然後執行：

【DECISIONS 月掃】
1. 更新「上次月掃 / 下次月掃」日期
2. 「近期已決」：超過 30 天的條目移除（確認對應決策案例已存在 03-決策案例庫/，不存在則列入回報）
3. 「決策中（醞釀型）」：比對近一個月的會議記錄與週記，「等的信號」出現了嗎？出現的標注「⚠️ 信號已到，待決」
4. 「待決（擱置型）」：截止訊號已過或 30 天內到期的標注提醒
5. 「結構性問題」：逐條檢查前提在當下還成立嗎？有變化的標注，附「繼續／修正／放棄」建議與證據

【決策回驗】
1. 「決策回驗總覽」中決定日超過 30 天但回驗結果空白的案例：打開對應案例檔，從會議記錄、週記、CHANGELOG 找實際結果的證據
2. 找得到 → 填一行摘要草稿（標「待確認」）；找不到 → 列入回報請我口頭補
3. 回驗結果與當初判斷有落差的案例特別標出——這是方法論升級的素材

【修正 log 月審】
1. 讀 10-操作手冊/修正log/ 上個月的 YYYY-MM_修正log.md（沒有這個檔就回報「上月無修正事件」）
2. 同類事件出現 2 次以上 → 起草一段補進 10-操作手冊/已知陷阱.md（標「待確認」）
3. 跨月反覆出現 → 起草 CLAUDE.md 修改提案，只列在回報裡，不改 CLAUDE.md
4. 其餘事件狀態填「不升級」＋一句理由

【完成後】
CHANGELOG.md 頂部補一行。
輸出回報：決策狀態總覽、信號已到待決清單、回驗完成與待補清單、判斷落差（若有）、修正 log 月審結果與 CLAUDE.md 提案（若有）。

原則：狀態標記直接做；回驗結論與規則提案一律標「待確認」，不擅自定論。"   --dangerously-skip-permissions   >> "$LOG_DIR/monthly-decision-scan_$(date +%F).log" 2>&1
